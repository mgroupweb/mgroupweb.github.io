// ---------------------------------------------------------------- helpers
function text(t, isError) { const o = { content: [{ type: 'text', text: t }] }; if (isError) o.isError = true; return o; }
function rpcResult(id, result) { return { jsonrpc: '2.0', id, result }; }
function rpcError(id, code, message) { return { jsonrpc: '2.0', id, error: { code, message } }; }
function json(o, status = 200, extra = {}) { return new Response(JSON.stringify(o), { status, headers: { ...CORS, 'Content-Type': 'application/json; charset=utf-8', ...extra } }); }
function num(v) { const n = parseFloat(v); return isFinite(n) && n >= 0 ? n : 0; }
function normalize(s) { return String(s || '').trim().toLowerCase().replace(/^https?:\/\//, '').replace(/^www\./, '').split(/[/?#]/)[0]; }
function decode(s) { return String(s || '').replace(/&#(\d+);/g, (_, n) => String.fromCharCode(n)).replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#8211;|&ndash;/g, '–').replace(/&#8217;/g, '’').replace(/<[^>]+>/g, ''); }
function htmlToText(h) { return h.replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>/gi, '').replace(/<[^>]+>/g, ' ').replace(/\s{2,}/g, ' ').trim(); }
function clientIp(req) {
  const cf = req.headers.get('CF-Connecting-IP') || '';
  if (ORIGIN_IPS.includes(cf)) return req.headers.get('X-Real-IP') || req.headers.get('X-Forwarded-For')?.split(',')[0].trim() || cf;
  return cf || 'x';
}
function memoGet(k) { const v = MEMO.get(k); if (v && v.exp > Date.now()) return v.val; MEMO.delete(k); return null; }
function memoSet(k, val, ttl) { if (MEMO.size > 200) MEMO.clear(); MEMO.set(k, { val, exp: Date.now() + ttl * 1000 }); }
async function getJson(u, ttl) {
  const c = memoGet('j:' + u); if (c) return c;
  try {
    const r = await fetch(u, { headers: { Accept: 'application/json', 'User-Agent': 'mgroup-mcp/' + VERSION } });
    if (!r.ok) return null;
    const d = await r.json(); memoSet('j:' + u, d, ttl); return d;
  } catch { return null; }
}
